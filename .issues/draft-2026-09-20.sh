set -euo pipefail

REPO="${REPO:-}"                      # empty = repo of the current directory
MODE=dry-run
[[ "${1:-}" == "--file" ]] && MODE=file

# This repo has only the default GitHub label set (bug, documentation,
# enhancement, duplicate, good first issue, help wanted, invalid, question,
# wontfix). The three severity labels used below do not exist yet.
# ensure_labels creates them; --force makes it idempotent (it updates an
# existing label instead of erroring). It runs only in --file mode, so a
# dry run still changes nothing in the repo.
ensure_labels() {
  gh label create critical --color b60205 --description "Must fix before the next release" --force ${REPO:+--repo "$REPO"}
  gh label create major    --color d93f0b --description "Significant defect or inaccuracy" --force ${REPO:+--repo "$REPO"}
  gh label create minor    --color fbca04 --description "Small defect or polish"           --force ${REPO:+--repo "$REPO"}
}

USED_LABELS=()

# Fail before anything is filed if any label used below is missing from the repo.
check_labels() {
  local have missing=()
  have="$(gh label list ${REPO:+--repo "$REPO"} --limit 500 --json name -q '.[].name')"
  for l in $(printf '%s\n' "${USED_LABELS[@]}" | sort -u); do
    grep -qxF "$l" <<<"$have" || missing+=("$l")
  done
  if ((${#missing[@]})); then
    echo "Missing labels: ${missing[*]}. Create them (see header) or edit this script." >&2
    exit 1
  fi
}

# issue "<title>" "<label>,<label>" <<'BODY' ... BODY
issue() {
  local title="$1" labels="$2" body
  body="$(cat)"
  if [[ $MODE == collect ]]; then
    IFS=, read -ra l <<<"$labels"
    USED_LABELS+=("${l[@]}")
  elif [[ $MODE == file ]]; then
    gh issue create ${REPO:+--repo "$REPO"} --title "$title" --label "$labels" --body "$body"
  else
    printf '=== %s  [%s]\n%s\n\n' "$title" "$labels" "$body"
  fi
}

