"""A driven series RLC circuit, drawn from circuit symbols built as paths.

The source, resistor, inductor and capacitor are each a short path generated by
a function of its end points, so the schematic is laid out by choosing where the
parts go. The figures quoted beside it ($\\omega_0$, $Q$, $\\zeta$, the damping
rate) are computed from $R$, $L$ and $C$.
"""
from __future__ import annotations

import math
import sys
from pathlib import Path

from diagrams_as_code import Diagram, Style
from diagrams_as_code.output import render_all

R, L, C = 100.0, 10e-3, 1e-6  # ohm, henry, farad
INK = "#111111"
WIRE = Style(fill="none", stroke=INK, stroke_width=2.0)
LEFT, RIGHT, TOP, BOTTOM = 110.0, 570.0, 110.0, 310.0


def seg(*pts) -> str:
    return "M " + " L ".join(f"{x:.2f} {y:.2f}" for x, y in pts)


def resistor(x0: float, x1: float, y: float, peaks: int = 6, amp: float = 11.0) -> str:
    """Zigzag between x0 and x1 with a 12 px lead at each end."""
    a, b = x0 + 12, x1 - 12
    pts = [(x0, y), (a, y)]
    step = (b - a) / peaks
    for k in range(peaks):
        pts.append((a + step * (k + 0.5), y + (-amp if k % 2 == 0 else amp)))
    pts += [(b, y), (x1, y)]
    return seg(*pts)


def inductor(x0: float, x1: float, y: float, loops: int = 4, lead: float = 12.0) -> str:
    """A row of semicircular humps between two leads."""
    a, b = x0 + lead, x1 - lead
    r = (b - a) / loops / 2
    d = f"M {x0:.2f} {y:.2f} L {a:.2f} {y:.2f}"
    for _ in range(loops):
        d += f" a {r:.2f} {r:.2f} 0 0 1 {2 * r:.2f} 0"
    return d + f" L {x1:.2f} {y:.2f}"


def capacitor(x: float, y0: float, y1: float, gap: float = 14.0, plate: float = 44.0) -> str:
    """Two parallel plates on a vertical wire from y0 to y1."""
    mid = (y0 + y1) / 2
    top, bot = mid - gap / 2, mid + gap / 2
    return (f"{seg((x, y0), (x, top))} {seg((x - plate / 2, top), (x + plate / 2, top))} "
            f"{seg((x - plate / 2, bot), (x + plate / 2, bot))} {seg((x, bot), (x, y1))}")


def sine(x: float, y: float, w: float = 26.0, h: float = 9.0) -> str:
    pts = [(x - w / 2 + w * i / 40, y - h * math.sin(2 * math.pi * i / 40)) for i in range(41)]
    return seg(*pts)


def diagram() -> Diagram:
    w0 = 1 / math.sqrt(L * C)
    f0 = w0 / (2 * math.pi)
    q = w0 * L / R
    zeta = 1 / (2 * q)
    alpha = R / (2 * L)
    wd = w0 * math.sqrt(1 - zeta ** 2) if zeta < 1 else 0.0
    mid_y = (TOP + BOTTOM) / 2
    r0, r1 = 200.0, 290.0     # resistor span
    l0, l1 = 360.0, 480.0     # inductor span
    with Diagram("Series RLC circuit", theme="paper") as diag:
        wires = [
            seg((LEFT, mid_y - 30), (LEFT, TOP), (r0, TOP)),
            seg((r1, TOP), (l0, TOP)),
            seg((l1, TOP), (RIGHT, TOP), (RIGHT, mid_y - 40)),
            seg((RIGHT, mid_y + 40), (RIGHT, BOTTOM), (LEFT, BOTTOM), (LEFT, mid_y + 30)),
        ]
        diag.path(" ".join(wires), style=WIRE)
        diag.path(resistor(r0, r1, TOP), style=WIRE)
        diag.path(inductor(l0, l1, TOP), style=WIRE)
        diag.path(capacitor(RIGHT, mid_y - 40, mid_y + 40), style=WIRE)
        # AC source: circle with a sine inside.
        rad = 30.0
        diag.path(
            f"M {LEFT - rad} {mid_y} A {rad} {rad} 0 1 0 {LEFT + rad} {mid_y} A {rad} {rad} 0 1 0 {LEFT - rad} {mid_y} Z",
            style=Style(fill="#FFFFFF", stroke=INK, stroke_width=2.0), z=1)
        diag.path(sine(LEFT, mid_y), style=Style(fill="none", stroke=INK, stroke_width=1.6), z=2)

        def text(s, x, y, anchor="center", size=14, **kw):
            diag.text(s, size=size, **kw).at(x, y, anchor=anchor)

        text("$v_s(t)$", LEFT - rad - 10, mid_y, anchor="right_center", size=15)
        text(f"$R = {R:g}\\,\\Omega$", (r0 + r1) / 2, TOP - 26, anchor="bottom_center")
        text(f"$L = {L * 1e3:g}\\,\\mathrm{{mH}}$", (l0 + l1) / 2, TOP - 26, anchor="bottom_center")
        text(f"$C = {C * 1e6:g}\\,\\mu\\mathrm{{F}}$", RIGHT + 40, mid_y, anchor="left_center")
        # Voltage drops under each part, current arrow on the top wire.
        text("$v_R$", (r0 + r1) / 2, TOP + 24, anchor="top_center", color="#9C2F2F")
        text("$v_L$", (l0 + l1) / 2, TOP + 24, anchor="top_center", color="#9C2F2F")
        text("$v_C$", RIGHT - 34, mid_y, anchor="right_center", color="#9C2F2F")
        diag.connect((LEFT + 40, TOP - 14), (LEFT + 80, TOP - 14), routing="direct", width=1.6, head="stealth")
        text("$i(t)$", LEFT + 60, TOP - 22, anchor="bottom_center")
        # Plus and minus on the capacitor.
        text("+", RIGHT + 30, mid_y - 30, size=14)
        text("−", RIGHT + 30, mid_y + 30, size=14)

        text(
            "Kirchhoff's voltage law around the loop:\n"
            "$v_s = L \\, di/dt + R \\, i + q / C$, with $i = dq/dt$,\n"
            "so $L \\, q'' + R \\, q' + q / C = v_s$.",
            LEFT - rad, BOTTOM + 36, anchor="top_left", size=13)
        text(
            f"$\\omega_0 = (LC)^{{-1/2}} = {w0:,.0f}$ rad/s  ($f_0 = {f0:,.0f}$ Hz)\n"
            f"$Q = \\omega_0 L / R = {q:.2f}$,  $\\zeta = 1 / 2Q = {zeta:.2f}$\n"
            f"decay rate $R / 2L = {alpha:,.0f}$ s$^{{-1}}$,  $\\omega_d = {wd:,.0f}$ rad/s",
            RIGHT + 40, TOP + 10, anchor="top_left", size=13)
        diag.caption("**Figure 3:** A series RLC circuit driven by an AC source, with the quantities that set its resonance",
                     small_caps=True)
    return diag


def build_diagram(output_dir: Path | str = "output/physics") -> Path:
    return render_all(diagram(), output_dir, "03_series_rlc_circuit")["svg"]


if __name__ == "__main__":
    dest = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("output/physics")
    build_diagram(dest)
