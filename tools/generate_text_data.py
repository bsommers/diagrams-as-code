#!/usr/bin/env python3
"""Generate the bundled text data: math glyph outlines and sans and serif advance widths.

Development-time only. Needs fontTools, which is not a project dependency:

    uv run --with fonttools python tools/generate_text_data.py \\
        --math-font /path/to/STIXTwoMath-Regular.otf \\
        --sans-regular /path/to/Arimo-Regular.ttf --sans-bold /path/to/Arimo-Bold.ttf \\
        --serif-regular /path/to/Tinos-Regular.ttf --serif-bold /path/to/Tinos-Bold.ttf \\
        --serif-italic /path/to/Tinos-Italic.ttf --serif-bold-italic /path/to/Tinos-BoldItalic.ttf

Each group of options is optional; only the modules whose fonts are given are rewritten.

Sources
    STIX Two Math 2.13 b171 — SIL Open Font License 1.1
        https://github.com/stipub/stixfonts (tag v2.13b171, fonts/static_otf)
    Arimo — Apache License 2.0 (metric-compatible with Arial and Helvetica)
        https://fonts.google.com/specimen/Arimo
    Tinos 1.340 — SIL Open Font License 1.1 (metric-compatible with Times New Roman and Times)
        https://github.com/google/fonts/tree/main/ofl/tinos

Only advance widths are taken from Arimo and Tinos; outlines are taken from STIX Two Math.
The generated modules are plain data and import nothing.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "src" / "diagrams_as_code" / "text"

ASCII = list(range(0x20, 0x7F))
MATH_ITALIC = list(range(0x1D434, 0x1D468)) + [0x210E]  # A-Z a-z (h lives at U+210E)
MATH_BOLD = list(range(0x1D400, 0x1D434))  # bold A-Z a-z
GREEK_UPPER = list(range(0x0391, 0x03AA))
GREEK_LOWER_ITALIC = list(range(0x1D6FC, 0x1D71C))  # alpha..omega, partial, variants
SYMBOLS = [ord(c) for c in (
    "¬±×÷·°′″‴…‖"
    "ℂℕℚℝℤℓℏ"
    "←↑→↓↔↕↦↝⇐⇒⇔⇝⟵⟶⟷⟹⟸⟺"
    "∀∁∂∃∄∅∆∇∈∉∋∌∎∏∐∑−∓∔∖∗∘∙√∝∞∟∠∣∤∥∦∧∨∩∪∫∬∮∴∵∶∷∼∽≀≁≂≃≄≅≈≉≍≐≔≕≜≝≟≠≡≢"
    "≤≥≦≧≪≫≮≯≲≳≺≻≼≽⊂⊃⊄⊅⊆⊇⊈⊉⊊⊋⊎⊏⊐⊑⊒⊓⊔⊕⊖⊗⊘⊙⊢⊣⊤⊥⊨⊩⋀⋁⋂⋃⋄⋅⋆⋮⋯⋰⋱"
    "⌈⌉⌊⌋⟨⟩⟦⟧⟂"
    "–—‘’“”•"
)]


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _round_path(d: str) -> str:
    out = []
    num = ""
    for ch in d:
        if ch.isdigit() or ch in "-.":
            num += ch
        else:
            if num:
                out.append(str(round(float(num))))
                num = ""
            out.append(ch)
    if num:
        out.append(str(round(float(num))))
    return "".join(out).replace(",", " ")


def build_math(font_path: Path) -> str:
    font = TTFont(str(font_path))
    upm = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    hmtx = font["hmtx"]
    wanted = sorted(set(ASCII + MATH_ITALIC + MATH_BOLD + GREEK_UPPER + GREEK_LOWER_ITALIC + SYMBOLS))
    rows = []
    missing = []
    for cp in wanted:
        name = cmap.get(cp)
        if name is None:
            missing.append(cp)
            continue
        pen = SVGPathPen(glyphs)
        glyphs[name].draw(pen)
        bounds = BoundsPen(glyphs)
        glyphs[name].draw(bounds)
        ymin, ymax = (bounds.bounds[1], bounds.bounds[3]) if bounds.bounds else (0, 0)
        rows.append((cp, hmtx[name][0], round(ymin), round(ymax), _round_path(pen.getCommands())))
    os2 = font["OS/2"]
    math = font["MATH"].table.MathConstants
    lines = [
        '"""Math glyph outlines. GENERATED by tools/generate_text_data.py -- do not edit.',
        "",
        "Outlines are derived from STIX Two Math 2.13 b171,",
        "Copyright 2001-2021 The STIX Fonts Project Authors (https://github.com/stipub/stixfonts),",
        "licensed under the SIL Open Font License, Version 1.1 (see OFL-STIX.txt beside this file).",
        f"Source file sha256: {_sha256(font_path)}",
        '"""',
        "",
        f"UNITS_PER_EM = {upm}",
        f"ASCENT = {os2.sTypoAscender}",
        f"DESCENT = {-os2.sTypoDescender}",
        f"CAP_HEIGHT = {os2.sCapHeight}",
        f"X_HEIGHT = {os2.sxHeight}",
        f"AXIS_HEIGHT = {math.AxisHeight.Value}",
        f"SUBSCRIPT_SHIFT_DOWN = {math.SubscriptShiftDown.Value}",
        f"SUPERSCRIPT_SHIFT_UP = {math.SuperscriptShiftUp.Value}",
        f"SCRIPT_PERCENT = {math.ScriptPercentScaleDown}",
        "",
        "#: codepoint -> (advance, ymin, ymax, path) in font units, y axis pointing up.",
        "GLYPHS: dict[int, tuple[int, int, int, str]] = {",
    ]
    for cp, adv, ymin, ymax, d in rows:
        lines.append(f"    0x{cp:X}: ({adv}, {ymin}, {ymax}, {d!r}),")
    lines.append("}")
    if missing:
        print("math font lacks:", " ".join(f"U+{cp:04X}" for cp in missing))
    return "\n".join(lines) + "\n"


def build_sans(regular: Path, bold: Path) -> str:
    def table(path: Path) -> tuple[dict[int, int], TTFont]:
        font = TTFont(str(path))
        cmap, hmtx = font.getBestCmap(), font["hmtx"]
        cps = [cp for cp in list(range(0x20, 0x7F)) + list(range(0xA0, 0x180)) + GREEK_UPPER
               + list(range(0x3B1, 0x3CA)) + SYMBOLS if cp in cmap]
        return {cp: hmtx[cmap[cp]][0] for cp in sorted(set(cps))}, font

    reg, font = table(regular)
    bld, _ = table(bold)
    upm = font["head"].unitsPerEm
    os2 = font["OS/2"]
    hhea = font["hhea"]

    def emit(name: str, widths: dict[int, int]) -> list[str]:
        out = [f"{name}: dict[int, int] = {{"]
        items = [f"0x{cp:X}: {w}" for cp, w in widths.items()]
        for i in range(0, len(items), 8):
            out.append("    " + ", ".join(items[i : i + 8]) + ",")
        out.append("}")
        return out

    lines = [
        '"""Sans-serif advance widths. GENERATED by tools/generate_text_data.py -- do not edit.',
        "",
        "Advance widths of Arimo (Apache License 2.0), which is metric-compatible with",
        "Arial and Helvetica. Only widths are recorded; no outlines.",
        f"Source sha256: regular {_sha256(regular)}",
        f"               bold    {_sha256(bold)}",
        '"""',
        "",
        f"UNITS_PER_EM = {upm}",
        f"ASCENT = {hhea.ascent}",
        f"DESCENT = {-hhea.descent}",
        f"CAP_HEIGHT = {getattr(os2, 'sCapHeight', 1467)}",
        f"X_HEIGHT = {getattr(os2, 'sxHeight', 1062)}",
        "",
        "#: codepoint -> advance in font units.",
        *emit("REGULAR", reg),
        "",
        *emit("BOLD", bld),
    ]
    return "\n".join(lines) + "\n"


def _cp1252() -> list[int]:
    """Every character a PDF standard font can show under WinAnsiEncoding."""
    out = []
    for byte in range(0x20, 0x100):
        try:
            out.append(ord(bytes([byte]).decode("cp1252")))
        except UnicodeDecodeError:
            pass
    return out


def build_serif(regular: Path, bold: Path, italic: Path, bold_italic: Path) -> str:
    faces = (("REGULAR", regular), ("BOLD", bold), ("ITALIC", italic), ("BOLD_ITALIC", bold_italic))
    lines = [
        '"""Serif advance widths. GENERATED by tools/generate_text_data.py -- do not edit.',
        "",
        "Advance widths of Tinos (SIL Open Font License 1.1), which is metric-compatible",
        "with Times New Roman and Times. Only widths are recorded; no outlines. The PDF",
        "writer uses them to place text set in the standard Times fonts.",
        "Source sha256:",
        *[f"    {name.lower():<12}{_sha256(path)}" for name, path in faces],
        '"""',
        "",
    ]
    upm = None
    for name, path in faces:
        font = TTFont(str(path))
        cmap, hmtx = font.getBestCmap(), font["hmtx"]
        if upm is None:
            upm = font["head"].unitsPerEm
            lines += [f"UNITS_PER_EM = {upm}", "", "#: codepoint -> advance in font units."]
        elif font["head"].unitsPerEm != upm:
            raise SystemExit(f"{path}: unitsPerEm differs from the regular face")
        widths = {cp: hmtx[cmap[cp]][0] for cp in sorted(_cp1252()) if cp in cmap}
        lines.append(f"{name}: dict[int, int] = {{")
        items = [f"0x{cp:X}: {w}" for cp, w in widths.items()]
        for k in range(0, len(items), 8):
            lines.append("    " + ", ".join(items[k : k + 8]) + ",")
        lines += ["}", ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--math-font", type=Path)
    parser.add_argument("--sans-regular", type=Path)
    parser.add_argument("--sans-bold", type=Path)
    parser.add_argument("--serif-regular", type=Path)
    parser.add_argument("--serif-bold", type=Path)
    parser.add_argument("--serif-italic", type=Path)
    parser.add_argument("--serif-bold-italic", type=Path)
    args = parser.parse_args()
    sans = (args.sans_regular, args.sans_bold)
    serif = (args.serif_regular, args.serif_bold, args.serif_italic, args.serif_bold_italic)
    for label, group in (("--sans-*", sans), ("--serif-*", serif)):
        if any(group) and not all(group):
            parser.error(f"give all of the {label} options or none")
    if not (args.math_font or all(sans) or all(serif)):
        parser.error("nothing to generate: give --math-font, --sans-* or --serif-*")
    OUT.mkdir(parents=True, exist_ok=True)
    written = []
    if args.math_font:
        (OUT / "_math_glyphs.py").write_text(build_math(args.math_font), encoding="utf-8")
        written.append("_math_glyphs.py")
    if all(sans):
        (OUT / "_sans_metrics.py").write_text(build_sans(*sans), encoding="utf-8")
        written.append("_sans_metrics.py")
    if all(serif):
        (OUT / "_serif_metrics.py").write_text(build_serif(*serif), encoding="utf-8")
        written.append("_serif_metrics.py")
    for name in written:
        print(f"wrote {OUT / name} ({(OUT / name).stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
