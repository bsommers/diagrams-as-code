#!/usr/bin/env python3
"""Generate the ``icons/`` tree and its manifests from ``ShapeLibrary``.

``ShapeLibrary._ICON_CATALOG`` is the single source of truth: it names every
canonical icon, the domain directory it lives in, and its one-line description.
Everything under ``icons/`` is emitted from that catalog and from the same
``_render_icon_content`` the SVG renderer uses, so a standalone icon file can
never drift from the glyph the engine draws.

Usage::

    uv run python tools/generate_icons.py            # write the tree
    uv run python tools/generate_icons.py --check    # verify, write nothing

``--check`` exits non-zero and lists every file that is missing, extra, or
stale. ``tests/test_icon_catalog.py`` runs it, so drift fails the suite.
"""

from __future__ import annotations

import argparse
import csv
import io
import re
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "src"))

from diagrams_as_code.shapes import ShapeLibrary  # noqa: E402

ICONS_DIR = REPO_ROOT / "icons"

#: Emitted into every standalone icon file. The engine renders icons inside a
#: positioned ``<g>``; a file needs its own root with the same 24x24 grid.
SVG_ROOT = (
    '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" '
    'viewBox="0 0 24 24" fill="none">'
)

#: Standalone files are monochrome and inherit color from the embedding page.
ICON_COLOR = "currentColor"
ICON_STROKE_WIDTH = 2

GENERATED_BY = "tools/generate_icons.py"


def _domains(library: ShapeLibrary) -> dict[str, list[str]]:
    """Group canonical icon names by domain directory, sorted throughout."""
    grouped: dict[str, list[str]] = defaultdict(list)
    for name, (domain, _description) in library._ICON_CATALOG.items():
        grouped[domain].append(name)
    return {domain: sorted(names) for domain, names in sorted(grouped.items())}


def render_icon_file(library: ShapeLibrary, name: str) -> str:
    """Return the full text of the standalone SVG file for ``name``."""
    content = library._render_icon_content(name, ICON_COLOR, ICON_STROKE_WIDTH)
    return f"{SVG_ROOT}\n{content}\n</svg>\n"


def render_csv(library: ShapeLibrary) -> str:
    """Return ``icons/icons.csv``: one row per canonical icon, sorted by name."""
    buffer = io.StringIO(newline="")
    writer = csv.writer(buffer, lineterminator="\n", quoting=csv.QUOTE_MINIMAL)
    writer.writerow(["symbol", "domain", "path", "notes"])
    for name in sorted(library._ICON_CATALOG):
        domain, description = library._ICON_CATALOG[name]
        writer.writerow([name, domain, f"./icons/{domain}/{name}.svg", description])
    return buffer.getvalue()


def _yaml_scalar(text: str) -> str:
    """Quote a YAML scalar. Descriptions are plain text; quote defensively."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_yaml(library: ShapeLibrary) -> str:
    """Return ``icons/icons.yaml``: the same catalog, grouped by domain."""
    domains = _domains(library)
    lines = [
        f"# Generated by {GENERATED_BY} -- do not edit by hand.",
        "# Source of truth: ShapeLibrary._ICON_CATALOG in"
        " src/diagrams_as_code/shapes.py",
        f"# Domains: {', '.join(domains)}",
        "",
    ]
    for domain, names in domains.items():
        for name in names:
            _domain, description = library._ICON_CATALOG[name]
            lines.append(f"- symbol: {name}")
            lines.append(f"  domain: {domain}")
            lines.append(f"  path: ./icons/{domain}/{name}.svg")
            lines.append(f"  notes: {_yaml_scalar(description)}")
    return "\n".join(lines) + "\n"


def _stroke_report(library: ShapeLibrary) -> str:
    """Describe the emitted set's stroke weights by measuring it.

    The claim about stroke geometry is computed from the files actually
    emitted, so it cannot drift away from the artwork the way a hand-written
    sentence can.
    """
    base = str(ICON_STROKE_WIDTH)
    accents: dict[str, list[str]] = {}
    for name in sorted(library._ICON_CATALOG):
        widths = set(re.findall(r'stroke-width="([^"]+)"', render_icon_file(library, name)))
        extra = sorted(widths - {base}, key=float)
        if extra:
            accents[name] = extra

    sentence = (
        f"Every icon is stroked at {base}px on the 24x24 grid and uses"
        " `currentColor`, so it inherits its color from the embedding document."
    )
    if accents:
        detail = ", ".join(
            f"`{name}` ({'/'.join(w + 'px' for w in widths)})"
            for name, widths in accents.items()
        )
        sentence += (
            f" {len(accents)} of {len(library._ICON_CATALOG)} add a lighter accent"
            f" stroke for interior detail: {detail}."
        )
    return sentence


def render_readme(library: ShapeLibrary) -> str:
    """Return ``icons/README.md``: counts and listings measured, not asserted."""
    domains = _domains(library)
    total = len(library._ICON_CATALOG)
    aliases = library._ICON_ALIASES

    lines = [
        "# Icon Catalog",
        "",
        f"<!-- Generated by {GENERATED_BY} -- do not edit by hand. -->",
        "",
        f"{total} monochrome vector icons on a 24x24 grid, one file per icon,",
        "across "
        f"{len(domains)} domain directories. Every file is emitted from",
        "`ShapeLibrary._ICON_CATALOG` by " + GENERATED_BY + ", so these files and",
        "the glyphs the renderer draws are the same artwork by construction.",
        "",
        _stroke_report(library),
        "",
        "## Authorship and licensing",
        "",
        "Every glyph is original geometry written for this project and is covered",
        "by the repository's [Apache-2.0 license](../LICENSE). No third-party icon set is",
        "vendored, traced, or redistributed here, and no upstream icon license",
        "obligations attach to it. See [`docs/sources.md`](../docs/sources.md) for",
        "the full provenance statement.",
        "",
        "## Domains",
        "",
    ]
    for domain, names in domains.items():
        count = len(names)
        noun = "icon" if count == 1 else "icons"
        lines.append(f"### `{domain}/` ({count} {noun})")
        lines.append("")
        for name in names:
            _domain, description = library._ICON_CATALOG[name]
            lines.append(f"- [`{name}.svg`]({domain}/{name}.svg) — {description}")
        lines.append("")

    lines += [
        "## Manifests",
        "",
        "- [`icons.csv`](icons.csv) — one row per icon: symbol, domain, path, notes.",
        "- [`icons.yaml`](icons.yaml) — the same catalog grouped by domain.",
        "",
        "## Aliases",
        "",
        f"`ShapeLibrary` accepts {len(aliases)} aliases in addition to the",
        f"{total} canonical names above. Some are vendor or product names"
        " (`grafana`,",
        "`kafka`, `s3`, `docker`): they are conveniences that resolve to the"
        " generic",
        "glyph named below. No vendor logo or trademarked mark is reproduced, and"
        " all",
        "product names remain the property of their respective owners.",
        "",
        "| Alias | Resolves to |",
        "| :--- | :--- |",
    ]
    for alias in sorted(aliases):
        lines.append(f"| `{alias}` | `{aliases[alias]}` |")
    lines.append("")

    lines += [
        "## Regenerating",
        "",
        "```bash",
        f"uv run python {GENERATED_BY}           # rewrite this directory",
        f"uv run python {GENERATED_BY} --check   # verify it is current",
        "```",
        "",
        "Add an icon by adding its glyph to `ShapeLibrary._render_icon_content`"
        " and",
        "its row to `ShapeLibrary._ICON_CATALOG`, then regenerate. Editing files"
        " in",
        "this directory by hand has no effect on rendering and will be"
        " overwritten.",
        "",
    ]
    return "\n".join(lines)


def build(library: ShapeLibrary) -> dict[Path, str]:
    """Return the full desired contents of ``icons/``, keyed by path."""
    files: dict[Path, str] = {}
    for name, (domain, _description) in library._ICON_CATALOG.items():
        files[ICONS_DIR / domain / f"{name}.svg"] = render_icon_file(library, name)
    files[ICONS_DIR / "icons.csv"] = render_csv(library)
    files[ICONS_DIR / "icons.yaml"] = render_yaml(library)
    files[ICONS_DIR / "README.md"] = render_readme(library)
    return files


def _existing_files() -> set[Path]:
    """Every file currently under ``icons/`` that the generator owns."""
    return {
        path
        for path in ICONS_DIR.rglob("*")
        if path.is_file() and path.suffix in {".svg", ".csv", ".yaml", ".md"}
    }


def check(files: dict[Path, str]) -> list[str]:
    """Return one problem string per missing, extra, or stale file."""
    problems = []
    for path, content in sorted(files.items()):
        if not path.exists():
            problems.append(f"missing: {path.relative_to(REPO_ROOT)}")
        elif path.read_text(encoding="utf-8") != content:
            problems.append(f"stale:   {path.relative_to(REPO_ROOT)}")
    for path in sorted(_existing_files() - set(files)):
        problems.append(f"extra:   {path.relative_to(REPO_ROOT)}")
    return problems


def write(files: dict[Path, str]) -> tuple[int, int]:
    """Write every file, removing ones the catalog no longer claims."""
    written = 0
    for path, content in sorted(files.items()):
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8")
            written += 1
    removed = 0
    for path in sorted(_existing_files() - set(files)):
        path.unlink()
        removed += 1
    for directory in sorted(ICONS_DIR.rglob("*"), reverse=True):
        if directory.is_dir() and not any(directory.iterdir()):
            directory.rmdir()
    return written, removed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the tree matches the catalog; write nothing",
    )
    args = parser.parse_args(argv)

    library = ShapeLibrary()
    files = build(library)

    # Every emitted SVG must parse as XML before it reaches disk.
    for path, content in files.items():
        if path.suffix != ".svg":
            continue
        try:
            ET.fromstring(content)
        except ET.ParseError as exc:
            print(f"error: {path.relative_to(REPO_ROOT)} is not well-formed: {exc}",
                  file=sys.stderr)
            return 1

    if args.check:
        problems = check(files)
        if problems:
            print(f"icons/ is out of date with ShapeLibrary._ICON_CATALOG "
                  f"({len(problems)} problem(s)):", file=sys.stderr)
            for problem in problems:
                print(f"  {problem}", file=sys.stderr)
            print(f"run: uv run python {GENERATED_BY}", file=sys.stderr)
            return 1
        print(f"icons/ is up to date ({len(files)} files).")
        return 0

    written, removed = write(files)
    print(f"icons/: {len(files)} files ({written} written, {removed} removed).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
